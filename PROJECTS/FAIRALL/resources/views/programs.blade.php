                        <p>The Fairplay Youth Center (formerly Fairplay Academy) aims to holistically support our Fairplay Scholars in all their needs: social support, academic tutoring, mental health support, and financial incentives. Each of these areas is crucial in order to break the cycle of poverty – without any one of them, more children will fall through the cracks and be unable to break that cycle.</p>
                        <p>The traditional style of education has been proven difficult to translate to poorer communities such as Payatas. Often, one child becomes the hope of the family and their school needs are provided, while the other children will work to support the family's basic needs. At Fairplay, we believe there's a better way.</p>
                        <p>Through the Youth Center, our Fairplay Scholars have access to: (1) social support through our weekly Youth Groups facilitated by our social and community workers, (2) academic tutoring through regular scheduled tutorials with our tutors, volunteers and community workers, (3) counseling through one-on-one "kamusthan" and consultation with the Youth Center Advisor as well as our weekly EQ Club and mentoring sessions, and (4) financial incentives through the Education Sponsorship Program's levels of support.</p>
